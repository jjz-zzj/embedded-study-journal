#include <stdio.h>

/**
 * 题目：输入一个温度值，如果大于 40 则打印告警，如果在 20~40 之间打印正常，否则打印低温。
 * 要求：使用 switch 语句完成。
 * 
 * 知识点避坑点：
 * 1. 【初学者最容易踩的坑】：不能直接写 `case > 40:`！
 *    C语言中 case 后面必须是【整型常量】（如 1, 2, 'A'），不能是判断表达式。
 * 2. 【switch 实现区间的核心思路】：
 *    将连续的连续温度区间，“映射”成离散的离散状态代码（例如 1代表告警，2代表正常，3代表低温）。
 */

int main()
{
    int temp = 0;
    printf("请输入当前环境温度 (整数摄氏度): ");
    if (scanf("%d", &temp) != 1) {
        printf("输入格式错误！\n");
        return 1;
    }

    // -------------------------------------------------------------
    // 方法一：三目运算符 / 状态映射法（标准 C 语言，全平台通用，最推荐）
    // -------------------------------------------------------------
    // 逻辑：如果 temp > 40，状态码为 1；否则如果 temp >= 20，状态码为 2；否则状态码为 3
    int status = (temp > 40) ? 1 : ((temp >= 20) ? 2 : 3);

    switch (status) {
        case 1:
            printf("[告警] 当前温度 %d°C：温度过高，请注意散热！\n", temp);
            break;
        case 2:
            printf("[正常] 当前温度 %d°C：机柜温度在正常工作区间 (20~40°C)。\n", temp);
            break;
        case 3:
            printf("[低温] 当前温度 %d°C：温度偏低，请检查加热模块。\n", temp);
            break;
        default:
            printf("未知状态。\n");
            break;
    }

    /*
    // -------------------------------------------------------------
    // 方法二（拓展知识）：GCC 编译器特有的区间扩展语法 (case 范围匹配)
    // 注意：这是 GCC/Clang 支持的语法，在嵌入式 Linux 和 STM32 GCC 开发中极常见，
    // 但不是 ANSI C 标准，注意三个点之间两边必须有空格！
    // -------------------------------------------------------------
    switch (temp) {
        case 41 ... 150:    // 大于 40 度
            printf("[GCC扩展-告警] 温度过高！\n");
            break;
        case 20 ... 40:     // 20 ~ 40 度
            printf("[GCC扩展-正常] 温度正常。\n");
            break;
        default:            // 其余情况（包括小于20度）
            printf("[GCC扩展-低温] 温度过低！\n");
            break;
    }
    */

    return 0;
}
