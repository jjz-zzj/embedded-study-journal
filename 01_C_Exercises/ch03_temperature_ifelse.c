#include <stdio.h>

/**
 * 题目：输入一个温度值，如果大于 40 则打印告警，如果在 20~40 之间打印正常，否则打印低温。
 * 解法：使用 if-else 级联条件分支（最地道、最自然的标准写法）
 * 
 * 避坑重点：
 * 1. 绝对不能写成数学写法 `if (20 <= temp <= 40)`！
 *    因为 C 语言会先算 `(20 <= temp)` 得到 0 或 1，然后再拿 0 或 1 去跟 40 比，永远为真！
 * 2. 正确写法必须用逻辑与 `&&` 连接：`temp >= 20 && temp <= 40`
 *    或者利用 if-else 的级联排除特性：先排除了 >40，剩下的必然 <=40，因此只需判断 `temp >= 20` 即可。
 */

int main()
{
    int temp = 0;
    printf("请输入当前环境温度 (摄氏度): ");
    if (scanf("%d", &temp) != 1) {
        printf("输入格式错误！\n");
        return 1;
    }

    // ---------------------------------------------------------
    // 级联 if-else 写法（从高到低逐级过滤）
    // ---------------------------------------------------------
    if (temp > 40) {
        printf("⚠️ [告警] 当前温度 %d°C：温度过高！\n", temp);
    } 
    else if (temp >= 20) {
        // 进入这个分支时，前提已经排除了 temp > 40，所以此时 temp 必定 <= 40
        // 这也是工业级 C 代码最常用的简化写法
        printf("✅ [正常] 当前温度 %d°C：温度适中 (20~40°C)。\n", temp);
    } 
    else {
        // 排除了 >40，也排除了 >=20，剩下的必然是 <20
        printf("❄️ [低温] 当前温度 %d°C：温度偏低！\n", temp);
    }

    return 0;
}
